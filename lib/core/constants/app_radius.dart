/// Corner radius tokens for the showcase design system.
///
/// Cards, buttons and inputs share a consistent radius language so shapes
/// feel cohesive across the app.
abstract final class AppRadius {
  /// Small pills and chips.
  static const double sm = 8;

  /// Default cards and small containers.
  static const double md = 12;

  /// Corners shared by most showcase cards.
  static const double lg = 16;

  /// Panels and larger containers.
  static const double xl = 20;

  /// Hero demo areas and dialogs.
  static const double xxl = 24;
}
